r"""Writes requirements.txt (what the app needs to RUN) and requirements-dev.txt (tests and building the EXE).

Run from the project root, in the project's virtual environment:

    python tools\make_requirements.py            # write both files
    python tools\make_requirements.py --check    # write nothing; exit 1 if the files are out of date

How it works: it reads every import in run_web_ui.py and app\\ (runtime) and in tests\\, tools\\ and
capture_form.py (dev), drops the standard library and your own modules, maps each import to the package that
provides it in THIS environment, and pins the installed version. Packages that are imported but not installed
are listed, never guessed. Only direct dependencies are listed; pip installs the rest.

Limits: it cannot see packages used only by name (PyInstaller is added to the dev file by hand) or
imports built from strings. Windows-only packages get a marker so the file also installs on other systems.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from importlib import metadata
from pathlib import Path

RUNTIME_ROOTS = ("run_web_ui.py", "app")
DEV_ROOTS = ("tests", "tools", "capture_form.py")
SKIP_DIRS = {"__pycache__", ".venv", "venv", "build", "dist", "node_modules", ".git", "mock", ".pytest_cache"}
# import name -> distribution, for when the metadata lookup cannot answer (package not installed)
KNOWN = {"win32com": "pywin32", "pythoncom": "pywin32", "pywintypes": "pywin32", "win32api": "pywin32",
         "win32timezone": "pywin32", "fitz": "pymupdf", "PIL": "pillow", "yaml": "pyyaml", "dotenv": "python-dotenv"}
WINDOWS_ONLY = {"pywin32"}
ALWAYS_DEV = ("pytest", "pytest-timeout", "pyinstaller")          # used by name, not by import
MARKER = '; sys_platform == "win32"'
HEADER = "# Generated by tools/make_requirements.py from the imports in the code and the packages installed in the\n" \
         "# environment it was run in. Re-run it after adding a dependency.\n"


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def source_files(root: Path, entries) -> list[Path]:
    files: list[Path] = []
    for entry in entries:
        path = root / entry
        if path.is_file():
            files.append(path)
        elif path.is_dir():
            files += [p for p in sorted(path.rglob("*.py")) if not SKIP_DIRS & set(p.relative_to(root).parts)]
    return files


def imported_names(path: Path) -> set[str]:
    """Top-level names of every absolute import, including ones inside functions and try/except blocks."""
    try:
        tree = ast.parse(path.read_bytes().decode("utf-8-sig"))
    except (SyntaxError, ValueError):
        return set()
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            names.add(node.module.split(".")[0])
    return names


def local_names(root: Path) -> set[str]:
    names = {p.stem for p in root.glob("*.py")}
    names |= {p.name for p in root.iterdir() if p.is_dir() and (p / "__init__.py").exists()}
    return names | {"app", "tests", "tools"}


def third_party(names: set[str], local: set[str]) -> set[str]:
    return {n for n in names if n not in sys.stdlib_module_names and n not in local and not n.startswith("_")}


def distribution_for(import_name: str, mapping: dict, known=KNOWN) -> str | None:
    dists = mapping.get(import_name)
    if dists:
        return sorted(dists)[0]
    return known.get(import_name)


def installed_version(dist: str) -> str | None:
    try:
        return metadata.version(dist)
    except metadata.PackageNotFoundError:
        return None


def resolve(names: set[str], mapping: dict, version_of=installed_version):
    """-> (requirement lines sorted, [import names with no installed package])."""
    pinned: dict[str, str] = {}
    missing: list[str] = []
    for name in sorted(names):
        dist = distribution_for(name, mapping)
        version = version_of(dist) if dist else None
        if not dist or not version:
            missing.append(f"{name}" + (f"  (package '{dist}')" if dist else ""))
            continue
        pinned[normalize(dist)] = f"{dist}=={version}" + (MARKER if normalize(dist) in WINDOWS_ONLY else "")
    return [pinned[k] for k in sorted(pinned)], missing


def build(root: Path, mapping=None, version_of=installed_version):
    mapping = metadata.packages_distributions() if mapping is None else mapping
    local = local_names(root)
    runtime_names = set().union(*(imported_names(p) for p in source_files(root, RUNTIME_ROOTS))) if source_files(root, RUNTIME_ROOTS) else set()
    dev_names = set().union(*(imported_names(p) for p in source_files(root, DEV_ROOTS))) if source_files(root, DEV_ROOTS) else set()
    runtime, runtime_missing = resolve(third_party(runtime_names, local), mapping, version_of)
    runtime_keys = {normalize(re.split(r"[=;]", line)[0]) for line in runtime}
    dev_only = third_party(dev_names, local)
    dev, dev_missing = resolve(dev_only, mapping, version_of)
    extra = []
    for dist in ALWAYS_DEV:
        version = version_of(dist)
        line = f"{dist}=={version}" if version else None
        if line and normalize(dist) not in runtime_keys and not any(normalize(re.split(r"[=;]", d)[0]) == normalize(dist) for d in dev):
            extra.append(line)
        elif not version:
            dev_missing.append(f"{dist}  (used by name; install it to pin it)")
    dev = sorted({d for d in dev + extra if normalize(re.split(r"[=;]", d)[0]) not in runtime_keys}, key=str.lower)
    return runtime, dev, runtime_missing, dev_missing


def render_runtime(lines) -> str:
    return HEADER + f"# Python {sys.version_info.major}.{sys.version_info.minor}\n" + "\n".join(lines) + "\n"


def render_dev(lines) -> str:
    return HEADER + "-r requirements.txt\n" + "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if the files differ")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    if not (root / "run_web_ui.py").is_file() or not (root / "app").is_dir():
        print(f"Not the KeyForMe project root (need run_web_ui.py and app\\): {root}")
        return 2
    runtime, dev, runtime_missing, dev_missing = build(root)
    files = {root / "requirements.txt": render_runtime(runtime), root / "requirements-dev.txt": render_dev(dev)}
    print(f"Runtime packages ({len(runtime)}):")
    for line in runtime:
        print("  " + line)
    print(f"Dev-only packages ({len(dev)}):")
    for line in dev:
        print("  " + line)
    for title, items in (("RUNTIME imports with NO installed package (the app would fail here)", runtime_missing),
                         ("dev imports with no installed package", dev_missing)):
        if items:
            print(f"\n{title}:")
            for item in items:
                print("  - " + item)
    if args.check:
        stale = [p.name for p, text in files.items()
                 if not p.is_file() or p.read_bytes().decode("utf-8-sig").replace("\r\n", "\n") != text]
        print("\nUp to date." if not stale else f"\nOut of date: {', '.join(stale)}")
        return 1 if stale or runtime_missing else 0
    for path, text in files.items():
        newline = "\r\n" if path.is_file() and b"\r\n" in path.read_bytes() else "\n"
        path.write_bytes(text.replace("\n", newline).encode("utf-8"))
    print("\nWrote requirements.txt and requirements-dev.txt")
    return 1 if runtime_missing else 0


if __name__ == "__main__":
    sys.exit(main())
